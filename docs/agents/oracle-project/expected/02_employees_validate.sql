SELECT 'TOTAL' AS RULE_NAME, 'INFO' AS SEVERITY, COUNT(*) AS VIOLATIONS FROM EMPLOYEES_RAW_CLEAN
UNION ALL
SELECT 'NN_EMPLOYEE_ID', 'ERROR', COUNT(*) FROM EMPLOYEES_RAW_CLEAN WHERE EMPLOYEE_ID IS NULL
UNION ALL
SELECT 'NN_EMPLOYEE_NAME', 'ERROR', COUNT(*) FROM EMPLOYEES_RAW_CLEAN WHERE EMPLOYEE_NAME IS NULL
UNION ALL
SELECT 'EMPLOYEES_PK', 'ERROR', COUNT(*) FROM (
SELECT EMPLOYEE_ID FROM EMPLOYEES_RAW_CLEAN
WHERE EMPLOYEE_ID IS NOT NULL
GROUP BY EMPLOYEE_ID HAVING COUNT(*) > 1
)
UNION ALL
SELECT 'EMPLOYEES_EMAIL_UK', 'WARN', COUNT(*) FROM (
SELECT EMAIL FROM EMPLOYEES_RAW_CLEAN
WHERE EMAIL IS NOT NULL
GROUP BY EMAIL HAVING COUNT(*) > 1
)
UNION ALL
SELECT 'EMPLOYEES_SALARY_CK', 'ERROR', COUNT(*) FROM EMPLOYEES_RAW_CLEAN WHERE NOT (SALARY >= 0)
;
