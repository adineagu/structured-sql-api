-- Accepted expected output, checked against the strategy; not validated in ODI.
TRUNCATE MAPPING IF EXISTS "OTP_DWH"."DWH_PREP"."PR_EMPLOYEES_TI_MAP";

CREATE OR REPLACE MAPPING "OTP_DWH"."DWH_PREP"."PR_EMPLOYEES_TI_MAP"
PHYSICAL DESIGN "Physical"
(
    OPTIMIZATION CONTEXT GLOBAL
    XKM "XKM Oracle Extract.GLOBAL" FOR TECHNOLOGY "Oracle"
    IKM "IKM Oracle Merge.GLOBAL" FOR TECHNOLOGY "Oracle"
    CKM "CKM Oracle.GLOBAL" FOR TECHNOLOGY "Oracle"
)
AS
INSERT INTO DWH_PREP.PR_EMPLOYEES (
    LOAD_ID,
    UPDATE_ID,
    LOAD_DATE,
    EFFECTIVE_DATE,
    EMPLOYEE_ID,
    DEPARTMENT_ID,
    SALARY
)
INTEGRATION TYPE 'Incremental Update'
UPDATE KEY PR_EMPLOYEES_UK
SELECT
    GET_LOAD_ID() AS LOAD_ID,
    GET_LOAD_ID() AS UPDATE_ID,
    SYSDATE AS LOAD_DATE,
    GET_EFFECTIVE_DATE() AS EFFECTIVE_DATE,
    E.EMPLOYEE_ID AS EMPLOYEE_ID,
    E.DEPARTMENT_ID AS DEPARTMENT_ID,
    E.SALARY AS SALARY
FROM DWH_STAGE.ST_EMPLOYEES E;
