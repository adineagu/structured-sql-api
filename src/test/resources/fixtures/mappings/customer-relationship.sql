@properties(
	INTEGRATION_TYPE = "Incremental Update",
	MAPPING_NAME = "CUSTOMER_RELATIONSHIP_LOAD",
	MAPPING_PATH = "DEMO.TRANSFORMATIONS",
	UPDATE_KEY = "CUSTOMER_RELATIONSHIP_UK"
)
INSERT INTO CUSTOMER_RELATIONSHIP (
	 SOURCE_OBJECT_ID
	,SOURCE_KEY_1
	,SOURCE_KEY_2
	,RELATED_CUSTOMER_ID
	,CREATED_BY
	,DATE_CREATED
	,DATE_MODIFIED
	,MODIFIED_BY
	,CUSTOMER_ID
	,RELATIONSHIP_CODE
)
WITH
SET_UNION_ALL AS (
@properties(name="CUSTOMER_RELATIONSHIPS") 
SELECT 
	 TO_CHAR(ST_CUSTOMER_RELATIONSHIPS.CUSTOMER_ID) as SOURCE_KEY_1
	,ST_CUSTOMER_RELATIONSHIPS.RELATIONSHIP_TYPE as SOURCE_KEY_2
	,GET_FK_REFERENCE(ST_CUSTOMER_RELATIONSHIPS.RELATED_CUSTOMER_ID,CUSTOMER_LOOKUP_RELATED.ID) as RELATED_CUSTOMER_ID
	,ST_CUSTOMER_RELATIONSHIPS.CREATED_BY as CREATED_BY
	,ST_CUSTOMER_RELATIONSHIPS.DATE_CREATED as DATE_CREATED
	,ST_CUSTOMER_RELATIONSHIPS.DATE_MODIFIED as DATE_MODIFIED
	,ST_CUSTOMER_RELATIONSHIPS.MODIFIED_BY as MODIFIED_BY
	,GET_FK_REFERENCE(ST_CUSTOMER_RELATIONSHIPS.CUSTOMER_ID,CUSTOMER_LOOKUP_PRIMARY.ID) as CUSTOMER_ID
	,TO_CHAR(GET_FK_REFERENCE(ST_CUSTOMER_RELATIONSHIPS.RELATIONSHIP_TYPE,RELATIONSHIP_LOOKUP.ID)) as RELATIONSHIP_CODE
	,'CUSTOMER_RELATIONSHIPS' as SOURCE_OBJECT
FROM 
ST_CUSTOMER_RELATIONSHIPS
LEFT JOIN CUSTOMER_LOOKUP CUSTOMER_LOOKUP_PRIMARY 
    ON ST_CUSTOMER_RELATIONSHIPS.CUSTOMER_ID = CUSTOMER_LOOKUP_PRIMARY.SOURCE_KEY_1
LEFT JOIN RELATIONSHIP_LOOKUP RELATIONSHIP_LOOKUP 
    ON ST_CUSTOMER_RELATIONSHIPS.RELATIONSHIP_TYPE = RELATIONSHIP_LOOKUP.SOURCE_KEY_1
LEFT JOIN CUSTOMER_LOOKUP CUSTOMER_LOOKUP_RELATED 
    ON ST_CUSTOMER_RELATIONSHIPS.RELATED_CUSTOMER_ID = CUSTOMER_LOOKUP_RELATED.SOURCE_KEY_1
WHERE
	CUSTOMER_LOOKUP_PRIMARY.SOURCE_OBJECT_ID = GET_SOURCE_OBJECT_ID('DEMO','CUSTOMERS') 
	AND RELATIONSHIP_LOOKUP.SOURCE_OBJECT_ID = GET_SOURCE_OBJECT_ID('DEMO','RELATIONSHIP_TYPES') 
	AND CUSTOMER_LOOKUP_RELATED.SOURCE_OBJECT_ID = GET_SOURCE_OBJECT_ID('DEMO','CUSTOMERS')
UNION ALL
@properties(name="CUSTOMER_RELATIONSHIP_HISTORY") 
SELECT 
	 RELATIONSHIP_HISTORY.SOURCE_KEY_1 as SOURCE_KEY_1
	,RELATIONSHIP_HISTORY.SOURCE_KEY_2 as SOURCE_KEY_2
	,RELATIONSHIP_HISTORY.RELATED_CUSTOMER_ID as RELATED_CUSTOMER_ID
	,RELATIONSHIP_HISTORY.CREATED_BY as CREATED_BY
	,RELATIONSHIP_HISTORY.DATE_CREATED as DATE_CREATED
	,RELATIONSHIP_HISTORY.DATE_MODIFIED as DATE_MODIFIED
	,RELATIONSHIP_HISTORY.MODIFIED_BY as MODIFIED_BY
	,RELATIONSHIP_HISTORY.CUSTOMER_ID as CUSTOMER_ID
	,TO_CHAR(RELATIONSHIP_HISTORY.RELATIONSHIP_CODE) as RELATIONSHIP_CODE
	,'CUSTOMER_RELATIONSHIP_HISTORY' as SOURCE_OBJECT
FROM 
RELATIONSHIP_HISTORY
WHERE
	RELATIONSHIP_HISTORY.SOURCE_OBJECT_ID = GET_SOURCE_OBJECT_ID('DEMO','CUSTOMER_RELATIONSHIP_HISTORY')
)
SELECT 
	 GET_SOURCE_OBJECT_ID('DEMO',SET_UNION_ALL.SOURCE_OBJECT) as SOURCE_OBJECT_ID
	,SET_UNION_ALL.SOURCE_KEY_1  as SOURCE_KEY_1
	,SET_UNION_ALL.SOURCE_KEY_2 as SOURCE_KEY_2
	,SET_UNION_ALL.RELATED_CUSTOMER_ID as RELATED_CUSTOMER_ID
	,SET_UNION_ALL.CREATED_BY as CREATED_BY
	,SET_UNION_ALL.DATE_CREATED as DATE_CREATED
	,SET_UNION_ALL.DATE_MODIFIED as DATE_MODIFIED
	,SET_UNION_ALL.MODIFIED_BY as MODIFIED_BY
	,SET_UNION_ALL.CUSTOMER_ID as CUSTOMER_ID
	,SET_UNION_ALL.RELATIONSHIP_CODE as RELATIONSHIP_CODE
FROM 
SET_UNION_ALL