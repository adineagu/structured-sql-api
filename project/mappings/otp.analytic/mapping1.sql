@properties(
	INTEGRATION_TYPE = "Incremental Update",
	MAPPING_NAME = "AD_ADDRESS_TI_MAP",
	MAPPING_PATH = "TEST_PRJ.TEST",
	UPDATE_KEY = "AD_ADDRESS_UK"
)
INSERT INTO AD_ADDRESS (
	 SOURCE_OBJECT_ID
	,SOURCE_KEY_1
	,SOURCE_KEY_2
	,ACCT_ASSOCIATION_ID
	,CREATED_BY
	,DATE_CREATED
	,DATE_MODIFIED
	,MODIFIED_BY
	,ACCT_ID
	,ACCT_ASSOCIATION_CODE
)
WITH
SET_UNION_ALL AS (
@properties(name="CNT_CONTURI_ASOCIERI") 
SELECT 
	 TO_CHAR(ST_ABS_CNT_CONTURI_ASOCIERI.CONT_ID) as SOURCE_KEY_1
	,ST_ABS_CNT_CONTURI_ASOCIERI.CONT_ASOCIERE_COD as SOURCE_KEY_2
	,GET_FK_REFERENCE(ST_ABS_CNT_CONTURI_ASOCIERI.CONT_ID_ASOCIERE,DW_ACCOUNTS_DAILY_ACCT_ASSOCIATION.ID) as ACCT_ASSOCIATION_ID
	,ST_ABS_CNT_CONTURI_ASOCIERI.CREATED_BY as CREATED_BY
	,ST_ABS_CNT_CONTURI_ASOCIERI.DATE_CREATED as DATE_CREATED
	,ST_ABS_CNT_CONTURI_ASOCIERI.DATE_MODIFIED as DATE_MODIFIED
	,ST_ABS_CNT_CONTURI_ASOCIERI.MODIFIED_BY as MODIFIED_BY
	,GET_FK_REFERENCE(ST_ABS_CNT_CONTURI_ASOCIERI.CONT_ID,DW_ACCOUNTS_DAILY_ACCT.ID) as ACCT_ID
	,TO_CHAR(GET_FK_REFERENCE(ST_ABS_CNT_CONTURI_ASOCIERI.CONT_ASOCIERE_COD,DW_ACCT_ASSOCIATION.ID)) as ACCT_ASSOCIATION_CODE
	,'CNT_CONTURI_ASOCIERI' as SOURCE_OBJECT
FROM 
ST_ABS_CNT_CONTURI_ASOCIERI
LEFT JOIN DW_ACCOUNTS_DAILY DW_ACCOUNTS_DAILY_ACCT 
    ON ST_ABS_CNT_CONTURI_ASOCIERI.CONT_ID = DW_ACCOUNTS_DAILY_ACCT.SOURCE_KEY_1
LEFT JOIN DW_ACCT_ASSOCIATION DW_ACCT_ASSOCIATION 
    ON ST_ABS_CNT_CONTURI_ASOCIERI.CONT_ASOCIERE_COD = DW_ACCT_ASSOCIATION.SOURCE_KEY_1
LEFT JOIN DW_ACCOUNTS_DAILY DW_ACCOUNTS_DAILY_ACCT_ASSOCIATION 
    ON ST_ABS_CNT_CONTURI_ASOCIERI.CONT_ID_ASOCIERE = DW_ACCOUNTS_DAILY_ACCT_ASSOCIATION.SOURCE_KEY_1
WHERE
	DW_ACCOUNTS_DAILY_ACCT.SOURCE_OBJECT_ID = GET_SOURCE_OBJECT_ID('ABS','CNT_CONTURI') 
	AND DW_ACCT_ASSOCIATION.SOURCE_OBJECT_ID = GET_SOURCE_OBJECT_ID('ABS','CNT_ASOCIERI') 
	AND DW_ACCOUNTS_DAILY_ACCT_ASSOCIATION.SOURCE_OBJECT_ID = GET_SOURCE_OBJECT_ID('ABS','CNT_CONTURI')
UNION ALL
@properties(name="CNT_CONTURI_ASOCIERI_IST") 
SELECT 
	 DW_ACCT_ASSOCIATION_MAP.SOURCE_KEY_1 as SOURCE_KEY_1
	,DW_ACCT_ASSOCIATION_MAP.SOURCE_KEY_2 as SOURCE_KEY_2
	,DW_ACCT_ASSOCIATION_MAP.ACCT_ASSOCIATION_ID as ACCT_ASSOCIATION_ID
	,DW_ACCT_ASSOCIATION_MAP.CREATED_BY as CREATED_BY
	,DW_ACCT_ASSOCIATION_MAP.DATE_CREATED as DATE_CREATED
	,DW_ACCT_ASSOCIATION_MAP.DATE_MODIFIED as DATE_MODIFIED
	,DW_ACCT_ASSOCIATION_MAP.MODIFIED_BY as MODIFIED_BY
	,DW_ACCT_ASSOCIATION_MAP.ACCT_ID as ACCT_ID
	,TO_CHAR(DW_ACCT_ASSOCIATION_MAP.ACCT_ASSOCIATION_CODE) as ACCT_ASSOCIATION_CODE
	,'CNT_CONTURI_ASOCIERI_IST' as SOURCE_OBJECT
FROM 
DW_ACCT_ASSOCIATION_MAP
WHERE
	DW_ACCT_ASSOCIATION_MAP.SOURCE_OBJECT_ID = GET_SOURCE_OBJECT_ID('ABS','CNT_CONTURI_ASOCIERI_IST')
)
SELECT 
	 GET_SOURCE_OBJECT_ID('ABS',SET_UNION_ALL.SOURCE_OBJECT) as SOURCE_OBJECT_ID
	,SET_UNION_ALL.SOURCE_KEY_1  as SOURCE_KEY_1
	,SET_UNION_ALL.SOURCE_KEY_2 as SOURCE_KEY_2
	,SET_UNION_ALL.ACCT_ASSOCIATION_ID as ACCT_ASSOCIATION_ID
	,SET_UNION_ALL.CREATED_BY as CREATED_BY
	,SET_UNION_ALL.DATE_CREATED as DATE_CREATED
	,SET_UNION_ALL.DATE_MODIFIED as DATE_MODIFIED
	,SET_UNION_ALL.MODIFIED_BY as MODIFIED_BY
	,SET_UNION_ALL.ACCT_ID as ACCT_ID
	,SET_UNION_ALL.ACCT_ASSOCIATION_CODE as ACCT_ASSOCIATION_CODE
FROM 
SET_UNION_ALL